-- =============================================================================
-- Dim_Product  (role-playing: Start Product / End Product)
-- Source: adw_prod10.dbo.PRODUCT_LOOKUP   Business key: PRODUCT_KEY   SCD: Type 1
-- =============================================================================

CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Product (
    ProductKey               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRODUCT_KEY              INT NOT NULL COMMENT 'Business key',
    ProductCode              STRING,
    ProductName              STRING,
    ProductType              STRING,
    BusinessLine             STRING COMMENT 'Life drives Active Increase/Decrease logic',
    BusinessSubLine          STRING,
    BusinessFund             STRING,
    ProductSeries            STRING,
    Series                   STRING,
    PremiumType              STRING,
    IssueType                STRING,
    IssuingCompany           STRING,
    ReportingBusinessGroup   STRING,
    ReportingEntity          STRING,
    CONSTRAINT pk_Dim_Product PRIMARY KEY (ProductKey) RELY
) USING DELTA COMMENT 'Product dimension';

INSERT INTO adw_prod10.star.Dim_Product (ProductKey, PRODUCT_KEY, ProductName, BusinessLine, ProductSeries, ReportingEntity)
SELECT -1, -1, 'Unknown', 'Unknown', 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Product WHERE ProductKey = -1);

CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Product AS
SELECT
    p.PRODUCT_KEY                    AS PRODUCT_KEY,
    trim(p.PRODUCT_CODE)             AS ProductCode,
    trim(p.PRODUCT_NAME)             AS ProductName,
    trim(p.PRODUCT_TYPE)             AS ProductType,
    trim(p.BUSINESS_LINE)            AS BusinessLine,
    trim(p.BUSINESS_SUB_LINE)        AS BusinessSubLine,
    trim(p.BUSINESS_FUND)            AS BusinessFund,
    trim(p.PRODUCT_SERIES)           AS ProductSeries,
    trim(p.SERIES)                   AS Series,
    trim(p.PREMIUM_TYPE)             AS PremiumType,
    trim(p.ISSUE_TYPE)               AS IssueType,
    trim(p.ISSUING_COMPANY)          AS IssuingCompany,
    trim(p.REPORTING_BUSINESS_GROUP) AS ReportingBusinessGroup,
    trim(p.REPORTING_ENTITY)         AS ReportingEntity
FROM adw_prod10.dbo.PRODUCT_LOOKUP AS p;

MERGE INTO adw_prod10.star.Dim_Product AS tgt
USING adw_prod10.star.stg_Dim_Product AS src
    ON tgt.PRODUCT_KEY = src.PRODUCT_KEY
WHEN MATCHED THEN UPDATE SET
    ProductCode = src.ProductCode, ProductName = src.ProductName, ProductType = src.ProductType,
    BusinessLine = src.BusinessLine, BusinessSubLine = src.BusinessSubLine, BusinessFund = src.BusinessFund,
    ProductSeries = src.ProductSeries, Series = src.Series, PremiumType = src.PremiumType,
    IssueType = src.IssueType, IssuingCompany = src.IssuingCompany,
    ReportingBusinessGroup = src.ReportingBusinessGroup, ReportingEntity = src.ReportingEntity
WHEN NOT MATCHED THEN INSERT
    (PRODUCT_KEY, ProductCode, ProductName, ProductType, BusinessLine, BusinessSubLine, BusinessFund,
     ProductSeries, Series, PremiumType, IssueType, IssuingCompany, ReportingBusinessGroup, ReportingEntity)
    VALUES
    (src.PRODUCT_KEY, src.ProductCode, src.ProductName, src.ProductType, src.BusinessLine, src.BusinessSubLine,
     src.BusinessFund, src.ProductSeries, src.Series, src.PremiumType, src.IssueType, src.IssuingCompany,
     src.ReportingBusinessGroup, src.ReportingEntity);
