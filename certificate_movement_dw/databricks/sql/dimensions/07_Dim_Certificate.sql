CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Certificate (
    CertificateKey          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADW_CERTIFICATE_KEY     STRING NOT NULL COMMENT 'Business key (text)',
    CertificateNumber       STRING,
    PolicyNo                STRING,
    OriginalCertificateNo   STRING,
    PlanCode                STRING,
    ProductTypeCode         STRING,
    CertificateContractType STRING,
    IssueDate               DATE,
    IssueAge                INT,
    Gender                  STRING,
    CurrentSmokerStatus     STRING,
    UnderwritingClass       STRING,
    CurrentStatus           STRING,
    CurrentRiskStatusGroup  STRING,
    DeathStatus             STRING,
    RescindedIndicator      STRING,
    MecIndicator            STRING,
    QualifiedIndicator      STRING,
    AgentName               STRING,
    AgentNumber             STRING,
    AgentStatus             STRING,
    MarketingGroupCode      STRING,
    SourceSystem            STRING,
    CountryCode             STRING,
    ZipPostalCode           STRING,
    CurrentIndicator        STRING,
    CONSTRAINT pk_Dim_Certificate PRIMARY KEY (CertificateKey) RELY
) USING DELTA COMMENT 'Certificate (policy) dimension';

INSERT INTO adw_prod10.star.Dim_Certificate (CertificateKey, ADW_CERTIFICATE_KEY, CertificateNumber, CurrentStatus)
SELECT -1, '-1', 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Certificate WHERE CertificateKey = -1);

CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Certificate AS
SELECT
    trim(c.ADW_CERTIFICATE_KEY)         AS ADW_CERTIFICATE_KEY,
    trim(c.CERTIFICATE_NUMBER)          AS CertificateNumber,
    trim(c.POLICY_NO)                   AS PolicyNo,
    trim(c.ORIGINAL_CERTIFICATE_NUMBER) AS OriginalCertificateNo,
    trim(c.PLAN_CODE)                   AS PlanCode,
    trim(c.PRODUCT_TYPE_CODE)           AS ProductTypeCode,
    trim(c.CERTIFICATE_CONTRACT_TYPE)   AS CertificateContractType,
    CAST(c.ISSUE_DATE AS DATE)          AS IssueDate,
    c.ISSUE_AGE                         AS IssueAge,
    trim(c.GENDER)                      AS Gender,
    trim(c.CURRENT_SMOKER_STATUS)       AS CurrentSmokerStatus,
    trim(c.UNDERWRITING_CLASS)          AS UnderwritingClass,
    trim(c.CURRENT_STATUS)              AS CurrentStatus,
    trim(c.CURRENT_RISK_STATUS_GROUP)   AS CurrentRiskStatusGroup,
    trim(c.DEATH_STATUS)                AS DeathStatus,
    trim(c.Rescinded_Indicator)         AS RescindedIndicator,
    trim(c.MEC_INDICATOR)               AS MecIndicator,
    trim(c.QUALIFIED_INDICATOR)         AS QualifiedIndicator,
    trim(c.AGENT_NAME)                  AS AgentName,
    trim(c.AGENT_NUMBER)                AS AgentNumber,
    trim(c.AGENT_STATUS)                AS AgentStatus,
    trim(c.MARKETING_GROUP_CODE)        AS MarketingGroupCode,
    trim(c.SOURCE_SYSTEM)               AS SourceSystem,
    trim(c.COUNTRY_CODE)                AS CountryCode,
    trim(c.ZIP_POSTAL_CODE)             AS ZipPostalCode,
    trim(c.CURRENT_INDICATOR)           AS CurrentIndicator
FROM adw_prod10.dbo.CERTIFICATE AS c;

MERGE INTO adw_prod10.star.Dim_Certificate AS tgt
USING adw_prod10.star.stg_Dim_Certificate AS src
    ON tgt.ADW_CERTIFICATE_KEY = src.ADW_CERTIFICATE_KEY
WHEN MATCHED THEN UPDATE SET
    CertificateNumber = src.CertificateNumber, PolicyNo = src.PolicyNo,
    OriginalCertificateNo = src.OriginalCertificateNo, PlanCode = src.PlanCode, ProductTypeCode = src.ProductTypeCode,
    CertificateContractType = src.CertificateContractType, IssueDate = src.IssueDate, IssueAge = src.IssueAge,
    Gender = src.Gender, CurrentSmokerStatus = src.CurrentSmokerStatus, UnderwritingClass = src.UnderwritingClass,
    CurrentStatus = src.CurrentStatus, CurrentRiskStatusGroup = src.CurrentRiskStatusGroup, DeathStatus = src.DeathStatus,
    RescindedIndicator = src.RescindedIndicator, MecIndicator = src.MecIndicator, QualifiedIndicator = src.QualifiedIndicator,
    AgentName = src.AgentName, AgentNumber = src.AgentNumber, AgentStatus = src.AgentStatus,
    MarketingGroupCode = src.MarketingGroupCode, SourceSystem = src.SourceSystem, CountryCode = src.CountryCode,
    ZipPostalCode = src.ZipPostalCode, CurrentIndicator = src.CurrentIndicator
WHEN NOT MATCHED THEN INSERT
    (ADW_CERTIFICATE_KEY, CertificateNumber, PolicyNo, OriginalCertificateNo, PlanCode, ProductTypeCode,
     CertificateContractType, IssueDate, IssueAge, Gender, CurrentSmokerStatus, UnderwritingClass, CurrentStatus,
     CurrentRiskStatusGroup, DeathStatus, RescindedIndicator, MecIndicator, QualifiedIndicator, AgentName,
     AgentNumber, AgentStatus, MarketingGroupCode, SourceSystem, CountryCode, ZipPostalCode, CurrentIndicator)
    VALUES
    (src.ADW_CERTIFICATE_KEY, src.CertificateNumber, src.PolicyNo, src.OriginalCertificateNo, src.PlanCode,
     src.ProductTypeCode, src.CertificateContractType, src.IssueDate, src.IssueAge, src.Gender, src.CurrentSmokerStatus,
     src.UnderwritingClass, src.CurrentStatus, src.CurrentRiskStatusGroup, src.DeathStatus, src.RescindedIndicator,
     src.MecIndicator, src.QualifiedIndicator, src.AgentName, src.AgentNumber, src.AgentStatus, src.MarketingGroupCode,
     src.SourceSystem, src.CountryCode, src.ZipPostalCode, src.CurrentIndicator);
