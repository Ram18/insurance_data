-- =============================================================================
-- Dim_Movement  — the transition dimension
-- Source: adw_prod10.dbo.MOVEMENT_MEASURE_LOOKUP
-- Business key: (ADW_STATUS_KEY_START, ADW_STATUS_KEY_END)   SCD: Type 1
-- =============================================================================

CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Movement (
    MovementKey           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADW_STATUS_KEY_START  INT NOT NULL COMMENT 'Business key part 1',
    ADW_STATUS_KEY_END    INT NOT NULL COMMENT 'Business key part 2',
    Movement              STRING,
    MovementGroup         STRING,
    StartFlag             INT,
    EndFlag               INT,
    NewFlag               INT,
    RevivedFlag           INT,
    ExitFlag              INT,
    LostFlag              INT,
    CorrectionFlag        INT,
    PremiumPayingAtStart  STRING,
    CONSTRAINT pk_Dim_Movement PRIMARY KEY (MovementKey) RELY
) USING DELTA COMMENT 'Start->End status transition dimension (movement classification + flags)';

INSERT INTO adw_prod10.star.Dim_Movement (MovementKey, ADW_STATUS_KEY_START, ADW_STATUS_KEY_END, Movement, MovementGroup,
    StartFlag, EndFlag, NewFlag, RevivedFlag, ExitFlag, LostFlag, CorrectionFlag)
SELECT -1, -1, -1, 'Unknown', 'Unknown', 0, 0, 0, 0, 0, 0, 0
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Movement WHERE MovementKey = -1);

CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Movement AS
SELECT
    m.ADW_STATUS_KEY_START            AS ADW_STATUS_KEY_START,
    m.ADW_STATUS_KEY_END              AS ADW_STATUS_KEY_END,
    trim(m.MOVEMENT)                  AS Movement,
    trim(m.MOVEMENT_GROUP)            AS MovementGroup,
    coalesce(m.START_FLAG, 0)         AS StartFlag,
    coalesce(m.END_FLAG, 0)           AS EndFlag,
    coalesce(m.NEW_FLAG, 0)           AS NewFlag,
    coalesce(m.REVIVED_FLAG, 0)       AS RevivedFlag,
    coalesce(m.EXIT_FLAG, 0)          AS ExitFlag,
    coalesce(m.LOST_FLAG, 0)          AS LostFlag,
    coalesce(m.CORRECTION_FLAG, 0)    AS CorrectionFlag,
    trim(m.PREMIUM_PAYING_AT_START)   AS PremiumPayingAtStart
FROM adw_prod10.dbo.MOVEMENT_MEASURE_LOOKUP AS m;

MERGE INTO adw_prod10.star.Dim_Movement AS tgt
USING adw_prod10.star.stg_Dim_Movement AS src
    ON  tgt.ADW_STATUS_KEY_START = src.ADW_STATUS_KEY_START
    AND tgt.ADW_STATUS_KEY_END   = src.ADW_STATUS_KEY_END
WHEN MATCHED THEN UPDATE SET
    Movement = src.Movement, MovementGroup = src.MovementGroup, StartFlag = src.StartFlag, EndFlag = src.EndFlag,
    NewFlag = src.NewFlag, RevivedFlag = src.RevivedFlag, ExitFlag = src.ExitFlag, LostFlag = src.LostFlag,
    CorrectionFlag = src.CorrectionFlag, PremiumPayingAtStart = src.PremiumPayingAtStart
WHEN NOT MATCHED THEN INSERT
    (ADW_STATUS_KEY_START, ADW_STATUS_KEY_END, Movement, MovementGroup, StartFlag, EndFlag,
     NewFlag, RevivedFlag, ExitFlag, LostFlag, CorrectionFlag, PremiumPayingAtStart)
    VALUES
    (src.ADW_STATUS_KEY_START, src.ADW_STATUS_KEY_END, src.Movement, src.MovementGroup, src.StartFlag, src.EndFlag,
     src.NewFlag, src.RevivedFlag, src.ExitFlag, src.LostFlag, src.CorrectionFlag, src.PremiumPayingAtStart);
