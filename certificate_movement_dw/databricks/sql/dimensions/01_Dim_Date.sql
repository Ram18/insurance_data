-- =============================================================================
-- Dim_Date  (role-playing: Period Start Date / Period End Date)
-- Source: adw_prod10.dbo.TIME_LOOKUP   Business key: TIME_KEY   SCD: Type 1
-- =============================================================================

CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Date (
    DateKey          BIGINT   GENERATED BY DEFAULT AS IDENTITY,
    TIME_KEY         INT      NOT NULL COMMENT 'Business (natural) key',
    AsOfDate         DATE,
    DayNumber        INT,
    DayName          STRING,
    MonthNumber      INT,
    MonthName        STRING,
    MonthAbbr        STRING,
    QuarterNumber    INT,
    YearNumber       INT,
    MonthYearName    STRING,
    QuarterYearName  STRING,
    JulianDate       INT,
    CurrentDateInd   STRING,
    CONSTRAINT pk_Dim_Date PRIMARY KEY (DateKey) RELY
) USING DELTA
  COMMENT 'Date / period-endpoint dimension';

-- Unknown member (-1)
INSERT INTO adw_prod10.star.Dim_Date (DateKey, TIME_KEY, DayName, MonthName, MonthYearName, QuarterYearName)
SELECT -1, -1, 'Unknown', 'Unknown', 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Date WHERE DateKey = -1);

-- Staging (trim text to match source Power Query Text.Trim)
CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Date AS
SELECT
    t.TIME_KEY                             AS TIME_KEY,
    CAST(t.AS_OF_DATE AS DATE)             AS AsOfDate,
    t.DAY_NUMBER                           AS DayNumber,
    trim(t.DAY_NAME)                       AS DayName,
    t.MONTH_NUMBER                         AS MonthNumber,
    trim(t.MONTH_NAME)                     AS MonthName,
    trim(t.MONTH_ABBR)                     AS MonthAbbr,
    t.QUARTER_NUMBER                       AS QuarterNumber,
    t.YEAR_NUMBER                          AS YearNumber,
    trim(t.MONTH_YEAR_NAME)                AS MonthYearName,
    trim(t.QUARTER_YEAR_NAME)              AS QuarterYearName,
    t.JULIAN_DATE                          AS JulianDate,
    trim(t.CURRENT_DATE_IND)               AS CurrentDateInd
FROM adw_prod10.dbo.TIME_LOOKUP AS t;

-- Type 1 load
MERGE INTO adw_prod10.star.Dim_Date AS tgt
USING adw_prod10.star.stg_Dim_Date AS src
    ON tgt.TIME_KEY = src.TIME_KEY
WHEN MATCHED THEN UPDATE SET
    AsOfDate = src.AsOfDate, DayNumber = src.DayNumber, DayName = src.DayName,
    MonthNumber = src.MonthNumber, MonthName = src.MonthName, MonthAbbr = src.MonthAbbr,
    QuarterNumber = src.QuarterNumber, YearNumber = src.YearNumber,
    MonthYearName = src.MonthYearName, QuarterYearName = src.QuarterYearName,
    JulianDate = src.JulianDate, CurrentDateInd = src.CurrentDateInd
WHEN NOT MATCHED THEN INSERT
    (TIME_KEY, AsOfDate, DayNumber, DayName, MonthNumber, MonthName, MonthAbbr,
     QuarterNumber, YearNumber, MonthYearName, QuarterYearName, JulianDate, CurrentDateInd)
    VALUES
    (src.TIME_KEY, src.AsOfDate, src.DayNumber, src.DayName, src.MonthNumber, src.MonthName, src.MonthAbbr,
     src.QuarterNumber, src.YearNumber, src.MonthYearName, src.QuarterYearName, src.JulianDate, src.CurrentDateInd);
