-- =============================================================================
-- Dim_Period
-- Source: adw_prod10.dbo.MOVEMENT_PERIODS   Business key: PERIOD_KEY   SCD: Type 1
-- =============================================================================

CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Period (
    PeriodKey            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PERIOD_KEY           INT NOT NULL COMMENT 'Business key',
    PeriodCode           STRING,
    PeriodStartCode      STRING,
    PeriodEndCode        STRING,
    TimeKeyStart         INT COMMENT '-> Dim_Date (Start role)',
    TimeKeyEnd           INT COMMENT '-> Dim_Date (End role)',
    YoyPeriods           STRING,
    QoqPeriods           STRING,
    YtdPeriods           STRING,
    MomPeriods           STRING,
    PeriodLoadFlag       STRING,
    CurrentReportInd     STRING,
    CurrentAnalysisInd   STRING,
    PeriodLength         DOUBLE,
    CONSTRAINT pk_Dim_Period PRIMARY KEY (PeriodKey) RELY
) USING DELTA COMMENT 'Movement reporting-period dimension';

INSERT INTO adw_prod10.star.Dim_Period (PeriodKey, PERIOD_KEY, PeriodCode)
SELECT -1, -1, 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Period WHERE PeriodKey = -1);

CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Period AS
SELECT
    p.PERIOD_KEY                 AS PERIOD_KEY,
    trim(p.PERIOD_CODE)          AS PeriodCode,
    trim(p.PERIOD_START_CODE)    AS PeriodStartCode,
    trim(p.PERIOD_END_CODE)      AS PeriodEndCode,
    p.TIME_KEY_START             AS TimeKeyStart,
    p.TIME_KEY_END               AS TimeKeyEnd,
    trim(p.YOY_PERIODS)          AS YoyPeriods,
    trim(p.QOQ_PERIODS)          AS QoqPeriods,
    trim(p.YTD_PERIODS)          AS YtdPeriods,
    trim(p.MOM_PERIODS)          AS MomPeriods,
    trim(p.PERIOD_LOAD_FLAG)     AS PeriodLoadFlag,
    trim(p.CURRENT_REPORT_IND)   AS CurrentReportInd,
    trim(p.CURRENT_ANALYSIS_IND) AS CurrentAnalysisInd,
    p.PERIOD_LENGTH              AS PeriodLength
FROM adw_prod10.dbo.MOVEMENT_PERIODS AS p;

MERGE INTO adw_prod10.star.Dim_Period AS tgt
USING adw_prod10.star.stg_Dim_Period AS src
    ON tgt.PERIOD_KEY = src.PERIOD_KEY
WHEN MATCHED THEN UPDATE SET
    PeriodCode = src.PeriodCode, PeriodStartCode = src.PeriodStartCode, PeriodEndCode = src.PeriodEndCode,
    TimeKeyStart = src.TimeKeyStart, TimeKeyEnd = src.TimeKeyEnd, YoyPeriods = src.YoyPeriods,
    QoqPeriods = src.QoqPeriods, YtdPeriods = src.YtdPeriods, MomPeriods = src.MomPeriods,
    PeriodLoadFlag = src.PeriodLoadFlag, CurrentReportInd = src.CurrentReportInd,
    CurrentAnalysisInd = src.CurrentAnalysisInd, PeriodLength = src.PeriodLength
WHEN NOT MATCHED THEN INSERT
    (PERIOD_KEY, PeriodCode, PeriodStartCode, PeriodEndCode, TimeKeyStart, TimeKeyEnd, YoyPeriods,
     QoqPeriods, YtdPeriods, MomPeriods, PeriodLoadFlag, CurrentReportInd, CurrentAnalysisInd, PeriodLength)
    VALUES
    (src.PERIOD_KEY, src.PeriodCode, src.PeriodStartCode, src.PeriodEndCode, src.TimeKeyStart, src.TimeKeyEnd,
     src.YoyPeriods, src.QoqPeriods, src.YtdPeriods, src.MomPeriods, src.PeriodLoadFlag, src.CurrentReportInd,
     src.CurrentAnalysisInd, src.PeriodLength);
