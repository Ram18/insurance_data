-- =============================================================================
-- Dim_Status  (role-playing: Start Status / End Status)
-- Source: adw_prod10.dbo.STATUS_LOOKUP   Business key: ADW_STATUS_KEY   SCD: Type 1
-- =============================================================================

CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Status (
    StatusKey                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADW_STATUS_KEY               INT NOT NULL COMMENT 'Business key',
    CertificateStatus            STRING,
    ClassCode                    STRING COMMENT 'Active/... drives movement logic',
    PremiumStatus                STRING,
    StudyStatusCode              STRING,
    StatusDescription            STRING,
    DisabilityStatus             STRING,
    AdminCertificateStatus       STRING,
    AdminCertificateStatusGroup  STRING,
    CONSTRAINT pk_Dim_Status PRIMARY KEY (StatusKey) RELY
) USING DELTA COMMENT 'Certificate status dimension';

INSERT INTO adw_prod10.star.Dim_Status (StatusKey, ADW_STATUS_KEY, CertificateStatus, ClassCode, StatusDescription)
SELECT -1, -1, 'Unknown', 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Status WHERE StatusKey = -1);

CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Status AS
SELECT
    s.ADW_STATUS_KEY                       AS ADW_STATUS_KEY,
    trim(s.CERTIFICATE_STATUS)             AS CertificateStatus,
    trim(s.CLASS_CODE)                     AS ClassCode,
    trim(s.PREMIUM_STATUS)                 AS PremiumStatus,
    trim(s.STUDY_STATUS_CODE)              AS StudyStatusCode,
    trim(s.STATUS_DESCRIPTION)             AS StatusDescription,
    trim(s.DISABILITY_STATUS)              AS DisabilityStatus,
    trim(s.ADMIN_CERTIFICATE_STATUS)       AS AdminCertificateStatus,
    trim(s.ADMIN_CERTIFICATE_STATUS_GROUP) AS AdminCertificateStatusGroup
FROM adw_prod10.dbo.STATUS_LOOKUP AS s;

MERGE INTO adw_prod10.star.Dim_Status AS tgt
USING adw_prod10.star.stg_Dim_Status AS src
    ON tgt.ADW_STATUS_KEY = src.ADW_STATUS_KEY
WHEN MATCHED THEN UPDATE SET
    CertificateStatus = src.CertificateStatus, ClassCode = src.ClassCode, PremiumStatus = src.PremiumStatus,
    StudyStatusCode = src.StudyStatusCode, StatusDescription = src.StatusDescription,
    DisabilityStatus = src.DisabilityStatus, AdminCertificateStatus = src.AdminCertificateStatus,
    AdminCertificateStatusGroup = src.AdminCertificateStatusGroup
WHEN NOT MATCHED THEN INSERT
    (ADW_STATUS_KEY, CertificateStatus, ClassCode, PremiumStatus, StudyStatusCode,
     StatusDescription, DisabilityStatus, AdminCertificateStatus, AdminCertificateStatusGroup)
    VALUES
    (src.ADW_STATUS_KEY, src.CertificateStatus, src.ClassCode, src.PremiumStatus, src.StudyStatusCode,
     src.StatusDescription, src.DisabilityStatus, src.AdminCertificateStatus, src.AdminCertificateStatusGroup);
