-- =============================================================================
-- Dim_Geography  (role-playing: Start Jurisdiction / End Jurisdiction)
-- Source: adw_prod10.dbo.GEOGRAPHIC_LOOKUP  Business key: JURISDICTION_KEY (text)  SCD: Type 1
-- =============================================================================

CREATE TABLE IF NOT EXISTS adw_prod10.star.Dim_Geography (
    GeographyKey            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    JURISDICTION_KEY        STRING NOT NULL COMMENT 'Business key (text)',
    JurisdictionCode        STRING,
    JurisdictionDescription STRING,
    StateCode               STRING COMMENT 'drives Relocate State logic',
    StateName               STRING,
    RegionCode              STRING,
    RegionName              STRING,
    CountryCode             STRING,
    CountryDescription      STRING,
    ContinentCode           STRING,
    ContinentDescription    STRING,
    CONSTRAINT pk_Dim_Geography PRIMARY KEY (GeographyKey) RELY
) USING DELTA COMMENT 'Geography / jurisdiction dimension';

INSERT INTO adw_prod10.star.Dim_Geography (GeographyKey, JURISDICTION_KEY, JurisdictionDescription, StateCode, CountryCode)
SELECT -1, '-1', 'Unknown', 'Unknown', 'Unknown'
WHERE NOT EXISTS (SELECT 1 FROM adw_prod10.star.Dim_Geography WHERE GeographyKey = -1);

CREATE OR REPLACE VIEW adw_prod10.star.stg_Dim_Geography AS
SELECT
    trim(g.JURISDICTION_KEY)         AS JURISDICTION_KEY,
    trim(g.JURISDICTION_CODE)        AS JurisdictionCode,
    trim(g.JURISDICTION_DESCRIPTION) AS JurisdictionDescription,
    trim(g.STATE_CODE)               AS StateCode,
    trim(g.STATE_NAME)               AS StateName,
    trim(g.REGION_CODE)              AS RegionCode,
    trim(g.REGION_NAME)              AS RegionName,
    trim(g.COUNTRY_CODE)             AS CountryCode,
    trim(g.COUNTRY_DESCRIPTION)      AS CountryDescription,
    trim(g.CONTINENT_CODE)           AS ContinentCode,
    trim(g.CONTINENT_DESCRIPTION)    AS ContinentDescription
FROM adw_prod10.dbo.GEOGRAPHIC_LOOKUP AS g;

MERGE INTO adw_prod10.star.Dim_Geography AS tgt
USING adw_prod10.star.stg_Dim_Geography AS src
    ON tgt.JURISDICTION_KEY = src.JURISDICTION_KEY
WHEN MATCHED THEN UPDATE SET
    JurisdictionCode = src.JurisdictionCode, JurisdictionDescription = src.JurisdictionDescription,
    StateCode = src.StateCode, StateName = src.StateName, RegionCode = src.RegionCode, RegionName = src.RegionName,
    CountryCode = src.CountryCode, CountryDescription = src.CountryDescription,
    ContinentCode = src.ContinentCode, ContinentDescription = src.ContinentDescription
WHEN NOT MATCHED THEN INSERT
    (JURISDICTION_KEY, JurisdictionCode, JurisdictionDescription, StateCode, StateName,
     RegionCode, RegionName, CountryCode, CountryDescription, ContinentCode, ContinentDescription)
    VALUES
    (src.JURISDICTION_KEY, src.JurisdictionCode, src.JurisdictionDescription, src.StateCode, src.StateName,
     src.RegionCode, src.RegionName, src.CountryCode, src.CountryDescription, src.ContinentCode, src.ContinentDescription);
